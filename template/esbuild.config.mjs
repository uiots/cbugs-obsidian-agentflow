import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { readFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;
const prod = process.argv[2] === "production";

const manifest = JSON.parse(
    readFileSync(new URL("./manifest.json", import.meta.url), "utf8"),
);

// CUSTOMIZE: dev mode can write main.js straight into the vault so that the
// hot-reload plugin sees the change immediately (mode A in docs/workflow.md).
// Provide OBSIDIAN_PLUGINS_DIR or a .vault-path file. Never hardcode a path.
function vaultOutfile(pluginId) {
    let dir = process.env.OBSIDIAN_PLUGINS_DIR || "";
    const vp = new URL("./.vault-path", import.meta.url);
    if (!dir && existsSync(vp)) dir = readFileSync(vp, "utf8").trim();
    if (!dir) return null;
    if (!existsSync(dir)) {
        console.error(`[build] ❌ OBSIDIAN_PLUGINS_DIR 不存在: ${dir}`);
        process.exit(1);
    }
    const target = join(dir, pluginId);
    mkdirSync(target, { recursive: true });
    return join(target, "main.js");
}

const outfile = prod ? "main.js" : vaultOutfile(manifest.id) || "main.js";

const context = await esbuild.context({
    banner: { js: banner },
    entryPoints: ["main.ts"],
    bundle: true,
    external: [
        "obsidian", "electron",
        "@codemirror/autocomplete", "@codemirror/collab", "@codemirror/commands",
        "@codemirror/language", "@codemirror/lint", "@codemirror/search",
        "@codemirror/state", "@codemirror/view",
        "@lezer/common", "@lezer/highlight", "@lezer/lr",
        ...builtins,
    ],
    format: "cjs",
    target: "es2018",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    outfile,
    minify: prod,
});

if (prod) {
    await context.rebuild();
    process.exit(0);
} else {
    if (outfile !== "main.js") {
        console.log(`[dev] watch → ${outfile}`);
        const d = dirname(outfile);
        if (!existsSync(join(d, "manifest.json"))) {
            console.warn("[dev] ⚠️ 首次请先运行 ./ob-sync.sh 同步 manifest.json / styles.css");
        }
    } else {
        console.log("[dev] 未配置 OBSIDIAN_PLUGINS_DIR / .vault-path，产物写在本地，需手动 ./ob-sync.sh");
    }
    await context.watch();
}
